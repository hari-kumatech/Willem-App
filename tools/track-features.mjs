#!/usr/bin/env node
// Keeps incremental_features/ and CHANGELOG.md in sync.
//
// Every top-level folder in incremental_features/ is one feature. When a new folder appears it gets the next
// INC number, an entry in CHANGELOG.md and a row in the index (incremental_features/README.md). When a folder
// disappears it is marked "removed" and logged; if it comes back it is registered again under a new number.
//
//   node tools/track-features.mjs            scan once and update the files
//   node tools/track-features.mjs --watch    keep running and update as soon as a folder is added or removed
//   node tools/track-features.mjs --check    only report; exit code 1 when something is not registered yet
//
// Runs automatically before every git commit (.githooks/pre-commit). Folders starting with "_" or "." are skipped
// (for example _TEMPLATE). Title and summary come from the folder's FEATURE.md, or else its first README.md.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync, watch } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FEATURES = join(ROOT, 'incremental_features');
const REGISTRY = join(FEATURES, 'registry.json');
const INDEX = join(FEATURES, 'README.md');
const CHANGELOG = join(ROOT, 'CHANGELOG.md');
const CHANGELOG_MARKER = '<!-- new entries go below this line (newest first) -->';
const INDEX_START = '<!-- AUTO-INDEX:START (generated by tools/track-features.mjs, do not edit by hand) -->';
const INDEX_END = '<!-- AUTO-INDEX:END -->';

const args = new Set(process.argv.slice(2));
const today = () => new Date().toLocaleDateString('sv-SE', { timeZone: 'Europe/Amsterdam' });
const posix = (p) => p.split('\\').join('/');

function loadRegistry() {
  if (!existsSync(REGISTRY)) return { features: [] };
  return JSON.parse(readFileSync(REGISTRY, 'utf8'));
}

function featureFolders() {
  if (!existsSync(FEATURES)) return [];
  return readdirSync(FEATURES, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith('_') && !d.name.startsWith('.'))
    .map((d) => d.name)
    .sort();
}

// FEATURE.md in the folder, else the shallowest README.md (max 2 levels deep, node_modules skipped)
function describeFile(folder) {
  const base = join(FEATURES, folder);
  if (existsSync(join(base, 'FEATURE.md'))) return join(base, 'FEATURE.md');
  let level = [base];
  for (let depth = 0; depth <= 2 && level.length; depth++) {
    for (const dir of level) if (existsSync(join(dir, 'README.md'))) return join(dir, 'README.md');
    level = level.flatMap((dir) =>
      readdirSync(dir, { withFileTypes: true })
        .filter((d) => d.isDirectory() && !['node_modules', '.git', 'data', 'public'].includes(d.name) && !d.name.startsWith('.'))
        .map((d) => join(dir, d.name))
        .sort(),
    );
  }
  return null;
}

function describe(folder) {
  const file = describeFile(folder);
  const fallback = { title: folder, summary: '', source: null };
  if (!file) return fallback;
  const lines = readFileSync(file, 'utf8').split(/\r?\n/);
  const heading = lines.findIndex((l) => /^#\s+\S/.test(l));
  const title = heading >= 0 ? lines[heading].replace(/^#\s+/, '').trim() : folder;
  const paragraph = [];
  const items = [];
  for (const line of lines.slice(heading + 1)) {
    const t = line.trim();
    const intro = paragraph.join(' ').trim().endsWith(':');
    // "Text:" followed by a list → summary is the text plus the list items' labels
    if (intro && /^[-*]\s+/.test(t)) {
      items.push(t.replace(/^[-*]\s+/, '').replace(/\*\*/g, '').split(/\s+[–—-]\s+/)[0].trim());
      continue;
    }
    if (!t) {
      if (paragraph.length && !intro) break;
      if (items.length) break;
      continue;
    }
    if (/^(#|```|>|\||<!--|---)/.test(t) || /^[-*]\s+\*\*/.test(t)) {
      if (paragraph.length) break;
      continue;
    }
    paragraph.push(t.replace(/^[-*]\s+/, ''));
  }
  let summary = `${paragraph.join(' ')}${items.length ? ` ${items.join(', ')}.` : ''}`.replace(/\s+/g, ' ').trim();
  if (summary.length > 220) summary = `${summary.slice(0, 217).replace(/\s+\S*$/, '')}…`;
  return { title, summary, source: posix(relative(ROOT, file)) };
}

function nextId(registry, changelog) {
  // Only real entries count (headings), not examples in the intro text
  const numbers = [...changelog.matchAll(/^###\s+INC-(\d+)/gm)].map((m) => Number(m[1]));
  numbers.push(...registry.features.map((f) => Number(f.id.slice(4))));
  return `INC-${String(Math.max(0, ...numbers) + 1).padStart(3, '0')}`;
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

function changelogEntry(kind, f, extra = '') {
  const link = `[incremental_features/${f.folder}](incremental_features/${encodeURI(f.folder)}/)`;
  if (kind === 'removed') {
    return [
      `### ${f.removedId} · ${f.removed} · Feature folder removed: ${f.title}`,
      '',
      `- **Type:** feature folder (registered automatically)`,
      `- **Folder:** \`incremental_features/${f.folder}\` (added as ${f.id}, folder no longer exists)`,
      '',
    ].join('\n');
  }
  return [
    `### ${f.id} · ${f.added} · Feature folder ${kind === 'readded' ? 're-added' : 'added'}: ${f.title}`,
    '',
    `- **Type:** feature folder (registered automatically)`,
    `- **Folder:** ${link}`,
    `- **Summary:** ${f.summary || '_No FEATURE.md or README.md yet: add one (see incremental_features/_TEMPLATE) and describe the feature here._'}`,
    ...(extra ? [`- **Note:** ${extra}`] : []),
    '',
  ].join('\n');
}

function renderIndex(registry) {
  const rows = [...registry.features].sort((a, b) => b.id.localeCompare(a.id));
  const table = [
    '| ID | Folder | Title | Summary | Added | Status |',
    '|---|---|---|---|---|---|',
    ...rows.map((f) =>
      `| ${f.id} | ${f.status === 'active' ? `[${cell(f.folder)}](${encodeURI(f.folder)}/)` : cell(f.folder)} | ${cell(f.title)} | ${cell(f.summary)} | ${f.added} | ${f.status === 'active' ? 'active' : `removed ${f.removed} (${f.removedId})`} |`,
    ),
  ];
  if (!rows.length) table.push('| | | _No feature folders yet._ | | | |');
  return `${INDEX_START}\n${table.join('\n')}\n${INDEX_END}`;
}

function sync({ write }) {
  const registry = loadRegistry();
  let changelog = existsSync(CHANGELOG) ? readFileSync(CHANGELOG, 'utf8') : `# Changelog\n\n${CHANGELOG_MARKER}\n`;
  if (!changelog.includes(CHANGELOG_MARKER)) throw new Error(`CHANGELOG.md is missing the marker line:\n${CHANGELOG_MARKER}`);
  const folders = featureFolders();
  const entries = [];
  const changes = [];

  for (const folder of folders) {
    const active = registry.features.find((f) => f.folder === folder && f.status === 'active');
    const info = describe(folder);
    if (active) {
      // Keep title / summary in the index up to date with the folder's own description
      if (active.title !== info.title || active.summary !== info.summary) {
        Object.assign(active, { title: info.title, summary: info.summary, source: info.source });
        changes.push(`updated description of ${active.id} ${folder}`);
      }
      continue;
    }
    const earlier = registry.features.filter((f) => f.folder === folder);
    const feature = { id: nextId(registry, changelog + entries.join('')), folder, ...info, added: today(), status: 'active', removed: null, removedId: null };
    registry.features.push(feature);
    const kind = earlier.length ? 'readded' : 'added';
    entries.push(changelogEntry(kind, feature, earlier.length ? `Earlier registered as ${earlier.map((f) => f.id).join(', ')}.` : ''));
    changes.push(`${kind === 'readded' ? 're-added' : 'added'} ${feature.id} ${folder}`);
  }

  for (const feature of registry.features) {
    if (feature.status !== 'active' || folders.includes(feature.folder)) continue;
    feature.status = 'removed';
    feature.removed = today();
    feature.removedId = nextId(registry, changelog + entries.join(''));
    entries.push(changelogEntry('removed', feature));
    changes.push(`removed ${feature.id} ${feature.folder} (${feature.removedId})`);
  }

  if (args.has('--check')) return changes;

  if (entries.length) {
    // Newest first: each new entry goes directly under the marker
    changelog = changelog.replace(CHANGELOG_MARKER, `${CHANGELOG_MARKER}\n\n${entries.reverse().join('\n').trimEnd()}\n`);
    changelog = changelog.replace(/\n{3,}/g, '\n\n');
  }
  let index = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : `# Incremental features\n\n${INDEX_START}\n${INDEX_END}\n`;
  const pattern = new RegExp(`${INDEX_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${INDEX_END}`);
  index = pattern.test(index) ? index.replace(pattern, renderIndex(registry)) : `${index.trimEnd()}\n\n${renderIndex(registry)}\n`;

  if (write) {
    registry.features.sort((a, b) => a.id.localeCompare(b.id));
    const registryText = `${JSON.stringify(registry, null, 2)}\n`;
    const writeIfChanged = (file, text) => {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== text) writeFileSync(file, text);
    };
    writeIfChanged(REGISTRY, registryText);
    writeIfChanged(INDEX, index);
    writeIfChanged(CHANGELOG, changelog);
  }
  return changes;
}

function report(changes) {
  if (!changes.length) return console.log('track-features: everything registered.');
  for (const c of changes) console.log(`track-features: ${c}`);
}

if (args.has('--check')) {
  const changes = sync({ write: false });
  report(changes);
  process.exit(changes.some((c) => !c.startsWith('updated')) ? 1 : 0);
} else if (args.has('--watch')) {
  report(sync({ write: true }));
  console.log(`Watching ${posix(relative(process.cwd(), FEATURES)) || '.'} for new or removed folders (Ctrl+C to stop)…`);
  let timer = null;
  watch(FEATURES, () => {
    clearTimeout(timer);
    // Wait until a copy / unzip has settled
    timer = setTimeout(() => {
      try {
        const changes = sync({ write: true });
        if (changes.length) report(changes);
      } catch (error) {
        console.error(error.message);
      }
    }, 2000);
  });
} else {
  if (!existsSync(FEATURES) || !statSync(FEATURES).isDirectory()) {
    console.error('incremental_features/ not found next to tools/.');
    process.exit(1);
  }
  report(sync({ write: true }));
}
