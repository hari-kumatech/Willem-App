// Database on this laptop: PostgreSQL + PostgREST in Docker (docker-compose.yml). No Supabase needed.
//
//   npm run db:start             start, generate missing secrets in .env.local, apply new migrations
//   npm run db:stop              stop (data is kept in the Docker volume mek-sales-hub_mek-db-data)
//   npm run db:migrate           apply migrations from db/migrations that have not run yet
//   npm run db:status            containers + applied migrations
//   npm run db:reset             wipe ALL data and rebuild from the migrations (asks first; --yes skips)
//   npm run db:psql              SQL shell
//   npm run db:backup            full backup to backups/mek-YYYY-MM-DD-HHMM.sql (schema, accounts and data)
//   npm run db:restore -- <file> replace the database with a backup (asks first; --yes skips)
//   npm run db:import-supabase   one-off: copy users and data from the old local Supabase database
import { execFileSync, spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, appendFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline/promises';
import { join } from 'node:path';

const ENV_FILE = '.env.local';
const MIGRATIONS = 'db/migrations';
const DB = 'mek-db';
const REST_URL = 'http://127.0.0.1:54331';

const [command = 'start', ...flags] = process.argv.slice(2);

function run(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['pipe', 'pipe', 'inherit'], ...opts });
}

function compose(...args) {
  const r = spawnSync('docker', ['compose', '--env-file', ENV_FILE, ...args], { stdio: 'inherit' });
  if (r.status !== 0) throw new Error(`docker compose ${args.join(' ')} failed`);
}

// psql inside the database container (no local PostgreSQL install needed)
function psql(sql, { quiet = true, vars = {} } = {}) {
  const args = ['exec', '-i', DB, 'psql', '-U', 'postgres', '-d', 'mek', '-v', 'ON_ERROR_STOP=1', '-At'];
  for (const [k, v] of Object.entries(vars)) args.push('-v', `${k}=${v}`);
  if (quiet) args.push('-q');
  return run('docker', args, { input: `set client_min_messages = warning;\n${sql}`, maxBuffer: 1024 * 1024 * 1024 });
}

// Creates the database secrets in .env.local the first time. Existing values are never changed.
function ensureEnv() {
  const text = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, 'utf8') : '';
  const has = (key) => new RegExp(`^${key}=.+`, 'm').test(text);
  const missing = [];
  if (!has('POSTGREST_URL')) missing.push(`POSTGREST_URL=${REST_URL}`);
  if (!has('AUTH_JWT_SECRET')) missing.push(`AUTH_JWT_SECRET=${randomBytes(32).toString('hex')}`);
  if (!has('POSTGRES_PASSWORD')) missing.push(`POSTGRES_PASSWORD=${randomBytes(16).toString('hex')}`);
  if (!has('AUTHENTICATOR_PASSWORD')) missing.push(`AUTHENTICATOR_PASSWORD=${randomBytes(16).toString('hex')}`);
  if (missing.length) {
    const header = text.includes('# --- Database') ? '' : '\n# --- Database (PostgreSQL + PostgREST, generated by npm run db:start) ---\n';
    appendFileSync(ENV_FILE, `${text && !text.endsWith('\n') ? '\n' : ''}${header}${missing.join('\n')}\n`);
    console.log(`Added to ${ENV_FILE}: ${missing.map((m) => m.split('=')[0]).join(', ')}`);
  }
  process.loadEnvFile(ENV_FILE);
}

function waitForDb() {
  for (let i = 0; i < 60; i++) {
    const r = spawnSync('docker', ['exec', DB, 'pg_isready', '-U', 'postgres', '-d', 'mek'], { stdio: 'ignore' });
    if (r.status === 0) return;
    spawnSync(process.execPath, ['-e', 'setTimeout(()=>{},1000)']);
  }
  throw new Error('PostgreSQL did not start within 60 seconds (docker logs mek-db)');
}

async function waitForRest() {
  for (let i = 0; i < 30; i++) {
    try {
      const res = await fetch(`${REST_URL}/`);
      if (res.status < 500) return true;
    } catch {
      // not up yet
    }
    await new Promise((r) => setTimeout(r, 1000));
  }
  return false;
}

function migrate() {
  psql('create schema if not exists app_meta; create table if not exists app_meta.schema_migrations (version text primary key, applied_at timestamptz not null default now());');
  const applied = new Set(psql('select version from app_meta.schema_migrations').split('\n').filter(Boolean));
  const files = readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort();
  let count = 0;
  for (const file of files) {
    const version = file.replace(/\.sql$/, '');
    if (applied.has(version)) continue;
    const sql = readFileSync(join(MIGRATIONS, file), 'utf8');
    // One transaction per migration, recorded only when it succeeds
    psql(`begin;\n${sql}\n;insert into app_meta.schema_migrations (version) values ('${version}');\ncommit;\n`);
    console.log(`  applied ${file}`);
    count++;
  }
  // PostgREST's login password follows .env.local
  psql(`alter role authenticator with login password :'pw';`, { vars: { pw: process.env.AUTHENTICATOR_PASSWORD } });
  psql(`notify pgrst, 'reload schema';`);
  console.log(count ? `${count} migration(s) applied.` : 'Database is up to date.');
}

async function start() {
  ensureEnv();
  compose('up', '-d', 'db');
  waitForDb();
  migrate();
  compose('up', '-d', 'rest');
  if (await waitForRest()) console.log(`Database ready (PostgREST ${REST_URL}, PostgreSQL 127.0.0.1:54332).`);
  else console.warn('PostgREST is not answering yet: docker logs mek-rest');
}

async function confirm(question) {
  if (flags.includes('--yes')) return true;
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const answer = await rl.question(`${question} Type "yes": `);
  rl.close();
  return answer.trim().toLowerCase() === 'yes';
}

async function reset() {
  if (!(await confirm('This deletes ALL data in the local database.'))) return console.log('Cancelled.');
  ensureEnv();
  compose('down', '-v');
  await start();
  console.log('Empty database. Open the app to create the admin account, then: npm run seed');
}

function status() {
  spawnSync('docker', ['ps', '-a', '--filter', 'name=mek-db', '--filter', 'name=mek-rest', '--format', 'table {{.Names}}\t{{.Status}}\t{{.Ports}}'], { stdio: 'inherit' });
  try {
    console.log('\nApplied migrations:');
    console.log(psql('select version || \'  \' || to_char(applied_at, \'YYYY-MM-DD HH24:MI\') from app_meta.schema_migrations order by version'));
  } catch {
    console.log('  (database not running)');
  }
}

// Copies accounts (bcrypt hashes, so passwords keep working) and all public tables from the old
// Supabase container into the new database. The target tables are emptied first.
async function importSupabase() {
  const names = run('docker', ['ps', '-a', '--filter', 'name=supabase_db_', '--format', '{{.Names}}']).split('\n').filter(Boolean);
  const source = flags.find((f) => !f.startsWith('--')) ?? names[0];
  if (!source) throw new Error('No Supabase database container found (docker ps -a --filter name=supabase_db_).');
  if (!(await confirm(`Copy users and data from ${source} into ${DB}? Current data in ${DB} is replaced.`))) return console.log('Cancelled.');
  spawnSync('docker', ['start', source], { stdio: 'ignore' });
  for (let i = 0; i < 30 && spawnSync('docker', ['exec', source, 'pg_isready', '-U', 'postgres'], { stdio: 'ignore' }).status !== 0; i++) {
    await new Promise((r) => setTimeout(r, 1000));
  }
  await start();

  const srcSql = (sql) => run('docker', ['exec', '-i', source, 'psql', '-U', 'postgres', '-d', 'postgres', '-At', '-v', 'ON_ERROR_STOP=1'], { input: sql });
  const tables = psql(`select tablename from pg_tables where schemaname = 'public' order by tablename`).split('\n').filter(Boolean);
  const sourceTables = new Set(srcSql(`select tablename from pg_tables where schemaname = 'public'`).split('\n').filter(Boolean));
  const common = tables.filter((t) => sourceTables.has(t));

  const users = srcSql(
    `copy (select id, lower(email), encrypted_password, coalesce(raw_user_meta_data, '{}'::jsonb), created_at from auth.users where email is not null and encrypted_password is not null) to stdout`,
  );
  const dump = run(
    'docker',
    ['exec', source, 'pg_dump', '-U', 'postgres', '-d', 'postgres', '--data-only', '--no-owner', '--no-privileges', ...common.flatMap((t) => ['-t', `public."${t}"`])],
    { maxBuffer: 1024 * 1024 * 1024 },
  );

  // Triggers and foreign keys off while loading (session_replication_role), so the profile trigger does not fire
  const script = [
    'begin;',
    'set session_replication_role = replica;',
    `truncate ${common.map((t) => `public."${t}"`).join(', ')}, auth.users cascade;`,
    ...(users.trim()
      ? ['copy auth.users (id, email, encrypted_password, raw_user_meta_data, created_at) from stdin;', users.trimEnd(), '\\.']
      : []),
    dump.replace(/^\\(un)?restrict .*$/gm, ''),
    'set session_replication_role = origin;',
    'commit;',
  ].join('\n');
  psql(script);
  console.log(`Imported ${users.split('\n').filter(Boolean).length} user(s) and ${common.length} tables from ${source}.`);
  for (const t of ['profiles', 'leads', 'companies', 'search_profiles', 'search_runs', 'quotes']) {
    if (common.includes(t)) console.log(`  ${t.padEnd(16)} ${psql(`select count(*) from public."${t}"`).trim()}`);
  }
  console.log(`You can stop the old container: docker stop ${source}`);
}

function backup() {
  mkdirSync('backups', { recursive: true });
  const stamp = new Date().toLocaleString('sv-SE', { timeZone: 'Europe/Amsterdam' }).slice(0, 16).replace(' ', '-').replace(':', '');
  const file = join('backups', `mek-${stamp}.sql`);
  // --clean: the file drops and recreates every object, so it restores over an existing database
  const sql = run('docker', ['exec', DB, 'pg_dump', '-U', 'postgres', '-d', 'mek', '--clean', '--if-exists', '--no-owner'], { maxBuffer: 1024 * 1024 * 1024 });
  writeFileSync(file, sql);
  console.log(`Backup written: ${file} (${(sql.length / 1024 / 1024).toFixed(1)} MB)`);
}

async function restore() {
  const file = flags.find((f) => !f.startsWith('--'));
  if (!file || !existsSync(file)) throw new Error('Usage: npm run db:restore -- backups/mek-….sql');
  if (!(await confirm(`Replace ALL data in the local database with ${file}?`))) return console.log('Cancelled.');
  ensureEnv();
  const sql = readFileSync(file, 'utf8').replace(/^\\(un)?restrict .*$/gm, '');
  psql(`begin;\n${sql}\ncommit;`);
  // pg_dump --clean drops the schemas, so restore the API privileges the bootstrap migration gave
  psql(readFileSync(join(MIGRATIONS, '20261001000000_postgres_bootstrap.sql'), 'utf8'));
  psql(`alter role authenticator with login password :'pw'; notify pgrst, 'reload schema';`, { vars: { pw: process.env.AUTHENTICATOR_PASSWORD } });
  console.log(`Restored ${file}.`);
}

const commands = {
  start,
  backup,
  restore,
  stop: () => compose('stop'),
  migrate: () => { ensureEnv(); migrate(); },
  status,
  reset,
  psql: () => spawnSync('docker', ['exec', '-it', DB, 'psql', '-U', 'postgres', '-d', 'mek'], { stdio: 'inherit' }),
  'import-supabase': importSupabase,
};

if (!commands[command]) {
  console.error(`Unknown command "${command}". Use: ${Object.keys(commands).join(', ')}`);
  process.exit(1);
}
try {
  await commands[command]();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
